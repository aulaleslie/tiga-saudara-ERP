    <strong>Pengaturan Printer Blueprint ECO80BT (Windows)</strong>
    <ul class="mb-2 mt-2 pl-3">
        <li>Hubungkan printer melalui USB dan pilih driver Blueprint ECO80BT di dialog cetak.</li>
        <li>Ukuran kertas: <strong>55 mm × 40 mm</strong>, media label gap (die-cut).</li>
        <li>Skala: <strong>Ukuran asli / 100%</strong>, tanpa margin, satu halaman per lembar.</li>
        <li>Salinan (copies) harus tetap <strong>1</strong> — jumlah label sudah digandakan oleh aplikasi.</li>
        <li>Header/footer dimatikan, duplex dimatikan, orientasi mengikuti ukuran label.</li>
    </ul>
    <div class="small mb-0">
        Aplikasi tidak dapat memilih printer, memaksa pengaturan driver, mendeteksi gangguan gap/media,
        atau memverifikasi bahwa label benar-benar tercetak. Kalibrasi media dilakukan di luar aplikasi.
    </div>
</div>
