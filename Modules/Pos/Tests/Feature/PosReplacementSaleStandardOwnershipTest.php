<?php

namespace Modules\Pos\Tests\Feature;

use App\Livewire\SalesReturn\SaleReferenceSearchDropdown;
use App\Livewire\SalesReturn\SaleReturnCreateForm;
use App\Livewire\SalesReturn\SaleReturnEditForm;
use App\Support\SalesReturn\SalesReturnWorkflowException;
use App\Support\SalesReturn\SalesReturnWorkflowResolver;
use Illuminate\Support\Facades\DB;
use Livewire\Livewire;
use Modules\Pos\Services\PosReturnLifecycleService;
use Modules\Pos\Tests\Feature\Support\BuildsSyntheticTransaction10717Fixture;
use Modules\Pos\Tests\Feature\Support\PosTransactionFeatureTestCase;
use Modules\SalesReturn\Entities\SaleReturn;

/** A replacement sale generated by the real lifecycle belongs to POS: standard create and mutation must refuse it. */
class PosReplacementSaleStandardOwnershipTest extends PosTransactionFeatureTestCase
{
    use BuildsSyntheticTransaction10717Fixture;

    private function generatedReplacementSaleId(): array
    {
        $fixture = $this->buildSyntheticTransaction10717Fixture('pending_approval');
        $this->actingAsInSetting($fixture['cashier'], $fixture['setting_a']);
        app(PosReturnLifecycleService::class)->executeApprovalFromPreview($fixture['pos_return']->id);

        $ids = DB::table('dispatch_details as dd')
            ->join('pos_return_lines as prl', 'prl.id', '=', 'dd.pos_return_line_id')
            ->whereNotNull('dd.sale_id')
            ->pluck('dd.sale_id')->map(fn ($i) => (int) $i)->unique()->values()->all();
        $replacementIds = array_values(array_diff($ids, [(int) $fixture['source_sale']->id]));
        $this->assertNotEmpty($replacementIds, 'Lifecycle must generate a cross-owner replacement sale.');

        return [$fixture, $replacementIds[0]];
    }

    /** Authorized standard-return user in the REPLACEMENT business (B), so permission/scope cannot be the refusal reason. */
    private function standardUserInReplacementBusiness(array $fixture)
    {
        \Spatie\Permission\Models\Permission::findOrCreate('saleReturns.create', 'web');
        $user = $this->createUserForSetting($fixture['setting_b'], 'Standard Return Clerk B', ['saleReturns.create']);
        $this->actingAsInSetting($user, $fixture['setting_b']);

        return $user;
    }

    /** @test */
    public function lifecycle_generated_replacement_sale_is_pos_and_real_standard_paths_refuse_it(): void
    {
        [$fixture, $saleId] = $this->generatedReplacementSaleId();
        $resolver = app(SalesReturnWorkflowResolver::class);
        $this->assertSame('pos', $resolver->classifySale($saleId));
        $sale = \Modules\Sale\Entities\Sale::withArchived()->findOrFail($saleId);
        $this->assertSame((int) $fixture['setting_b']->id, (int) $sale->setting_id, 'replacement belongs to business B');

        $this->standardUserInReplacementBusiness($fixture);
        $this->assertTrue(\Illuminate\Support\Facades\Gate::allows('saleReturns.create'), 'user is authorized');

        $expected = null;
        try {
            $resolver->assertSaleAllowsStandardReturn($saleId);
        } catch (SalesReturnWorkflowException $e) {
            $expected = $e->getMessage();
        }
        $this->assertStringContainsString('Retur POS', (string) $expected);

        // Record every ownership refusal raised by the production guard (flash messages are not visible to the test).
        $spy = new class extends SalesReturnWorkflowResolver {
            public array $refusals = [];

            public function assertSaleAllowsStandardReturn(int $saleId): void
            {
                try {
                    parent::assertSaleAllowsStandardReturn($saleId);
                } catch (SalesReturnWorkflowException $e) {
                    $this->refusals[] = [$saleId, $e->getMessage()];
                    throw $e;
                }
            }
        };
        app()->instance(SalesReturnWorkflowResolver::class, $spy);

        // Valid, authoritative rows exactly as the form would build them.
        $rows = app(\App\Support\SalesReturn\SaleReturnEligibilityService::class)->summariseSale($sale->load(['saleDetails.product', 'saleDetails.bundleItems', 'saleDispatches.details.product', 'saleDispatches.details.location']))['rows']->all();
        // Claim exactly one unit with its real serial so form validation passes and ONLY ownership can refuse.
        $rows = array_slice($rows, 0, 1);
        $serial = \Modules\Product\Entities\ProductSerialNumber::query()->where('dispatch_detail_id', $rows[0]['dispatch_detail_id'] ?? 0)->first();
        $rows[0]['quantity'] = 1;
        $rows[0]['total'] = (float) $rows[0]['unit_price'];
        if ($serial) {
            $rows[0]['serial_numbers'] = [['id' => $serial->id, 'serial_number' => $serial->serial_number]];
        }
        $this->assertNotEmpty($rows, 'replacement sale offers valid returnable rows, so only ownership can refuse');
        $before = SaleReturn::withArchived()->count();

        // Lookup hides the sale.
        Livewire::test(SaleReferenceSearchDropdown::class)->set('search', $sale->reference)->assertSet('options', []);

        // Direct payload selection: refused with the ownership message, nothing selected.
        Livewire::test(SaleReturnCreateForm::class)
            ->call('handleSaleSelected', ['id' => $saleId, 'rows' => $rows, 'reference' => $sale->reference])
            ->assertSet('sale_id', null);
        $this->assertSame([[$saleId, $expected]], $spy->refusals);

        // Submit with valid rows: 200 (not 403), refused by ownership, nothing written.
        Livewire::test(SaleReturnCreateForm::class)
            ->set('sale_id', $saleId)
            ->set('rows', $rows)
            ->call('submit')
            ->assertOk()
            ->assertHasNoErrors();
        $this->assertSame([[$saleId, $expected], [$saleId, $expected]], $spy->refusals, 'submit reached and failed the ownership guard: ' . json_encode($spy->refusals));
        $this->assertSame($before, SaleReturn::withArchived()->count());
    }

    /** @test */
    public function standard_return_on_a_generated_replacement_sale_is_mixed_and_every_mutation_is_refused_unchanged(): void
    {
        [$fixture, $saleId] = $this->generatedReplacementSaleId();
        DB::statement('PRAGMA defer_foreign_keys = ON');
        $template = $fixture['sale_return']->toArray();
        unset($template['id']);
        $standard = SaleReturn::query()->create(array_merge($template, [
            'sale_id' => $saleId, 'pos_return_id' => null, 'reference' => 'SR-STD-' . uniqid(),
        ]));
        $snapshot = $standard->fresh()->toArray();
        $resolver = app(SalesReturnWorkflowResolver::class);

        $this->assertSame('mixed', $resolver->classifySale($saleId));

        Livewire::test(SaleReturnEditForm::class, ['saleReturn' => $standard])->assertStatus(409);

        try {
            $resolver->assertStandardMutable($standard);
            $this->fail('Mixed history must refuse standard mutation.');
        } catch (SalesReturnWorkflowException $e) {
            $this->assertSame(409, $e->getStatusCode());
        }
        $this->assertSame($snapshot, $standard->fresh()->toArray());
    }
}
